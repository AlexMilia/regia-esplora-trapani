-- =====================================================================
-- IL RILIEVO SUL CAMPO · le scene come piano di ripresa
-- Progetto: sdqzqzmkhbkkibjzauox. Un blocco solo: incolla ed esegui.
-- Si può rieseguire quante volte vuoi.
--
-- L'IDEA
--   Il piano di ripresa È l'elenco delle scene. Una scena può nascere PRIMA
--   di andare sul posto, senza panorama: è un punto sulla pianta che aspetta
--   lo scatto. Sul campo si tocca («sono qui»), a casa si riempie. Stessa
--   riga di story_tour_scene dall'inizio alla fine: niente tabelle parallele.
--
-- LO STATO NON SI SCRIVE, SI LEGGE
--   stato_rilievo è una colonna CALCOLATA dal database:
--     da_riprendere · nessun panorama, nessun tocco
--     scattata      · toccata sul campo, panorama ancora vuoto
--     abbinata      · ha il panorama, non è ancora nel tour
--     pubblicata    · ha il panorama ed è attiva
--   Così non può mai andare in disaccordo con i dati veri. Non si assegna
--   a mano: il database rifiuta la scrittura, ed è giusto così.
--
-- IL PARAPETTO
--   Una scena senza panorama non può essere attiva: il tour mostrerebbe un
--   buco. Se qualcuno la accende, il database la rispegne.
-- =====================================================================

begin;

-- ── 1 · LA GIORNATA DI RIPRESE ──────────────────────────────────────
-- Uno scarto d'orologio per sessione, non per scena. E l'intervallo di tempo
-- che dice quali scatti appartengono a QUESTO rilievo e non a quello dopo.
create table if not exists public.story_rilievo (
  id                 bigint generated by default as identity primary key,
  poi_id             bigint not null references public.story_poi(id) on delete cascade,
  iniziato_il        timestamptz default now(),
  finito_il          timestamptz,
  scarto_orologio_ms integer default 0,     -- fotocamera − telefono, in millisecondi
  sync_toccato_il    timestamptz,           -- il tocco «sincronizza», da confrontare col primo scatto
  cartella_b2        text,                  -- dove hai scaricato la fotocamera
  dispositivo        text,                  -- 'x6' · 'avata' · altro: dice quale abbinamento usare
  note               text,
  creato_il          timestamptz default now()
);
create index if not exists idx_rilievo_poi on public.story_rilievo(poi_id, iniziato_il desc);
alter table public.story_rilievo enable row level security;
drop policy if exists "lettura pubblica rilievo" on public.story_rilievo;
create policy "lettura pubblica rilievo" on public.story_rilievo for select using (true);

-- ── 2 · LA SCENA COME PUNTO DEL PIANO ───────────────────────────────
-- il panorama può mancare: è il punto che aspetta lo scatto
alter table public.story_tour_scene alter column panorama drop not null;

alter table public.story_tour_scene add column if not exists rilievo_id       bigint references public.story_rilievo(id) on delete set null;
alter table public.story_tour_scene add column if not exists toccata_il       timestamptz;   -- l'ora del tocco sul campo
alter table public.story_tour_scene add column if not exists scatti_candidati text[] default '{}';  -- gli altri scatti dello stesso punto
alter table public.story_tour_scene add column if not exists foto_campo       text;          -- la foto del telefono, per la revisione
alter table public.story_tour_scene add column if not exists nota_campo       text;
alter table public.story_tour_scene add column if not exists lat_campo        numeric;       -- dove eri al tocco, quando il cielo si vede
alter table public.story_tour_scene add column if not exists lng_campo        numeric;
alter table public.story_tour_scene add column if not exists yaw_proposto     numeric;       -- dalla bussola del file: PROPOSTA, non certezza
alter table public.story_tour_scene add column if not exists abbinata_il      timestamptz;

-- lo stato, calcolato: non può disallinearsi
do $$
begin
  if not exists (select 1 from information_schema.columns
                  where table_schema='public' and table_name='story_tour_scene' and column_name='stato_rilievo') then
    alter table public.story_tour_scene add column stato_rilievo text
      generated always as (
        case
          when coalesce(panorama,'') <> '' and attivo is true then 'pubblicata'
          when coalesce(panorama,'') <> ''                    then 'abbinata'
          when toccata_il is not null                         then 'scattata'
          else 'da_riprendere'
        end
      ) stored;
  end if;
end $$;
create index if not exists idx_tour_scene_stato on public.story_tour_scene(poi_id, stato_rilievo);

-- ── 3 · IL PARAPETTO ────────────────────────────────────────────────
create or replace function public.story_tour_scene_parapetto() returns trigger
language plpgsql as $$
begin
  if coalesce(new.panorama,'') = '' then
    new.panorama := null;            -- niente stringhe vuote in giro
    new.attivo   := false;           -- senza panorama non si va nel tour
  end if;
  -- il momento dell'abbinamento, una volta sola
  if coalesce(new.panorama,'') <> '' and (tg_op = 'INSERT' or coalesce(old.panorama,'') = '') then
    new.abbinata_il := coalesce(new.abbinata_il, now());
  end if;
  return new;
end $$;
drop trigger if exists trg_tour_scene_parapetto on public.story_tour_scene;
create trigger trg_tour_scene_parapetto
before insert or update on public.story_tour_scene
for each row execute function public.story_tour_scene_parapetto();

-- rattoppo per le righe che ci sono già
update public.story_tour_scene set panorama = null where panorama = '';
update public.story_tour_scene set attivo = false where panorama is null and attivo is true;

-- ── 4 · IL NORD DELLA PLANIMETRIA ───────────────────────────────────
-- gradi in senso orario dall'alto della pianta: serve per tradurre una
-- bussola (drone) in yaw. Una volta per luogo, opzionale.
alter table public.story_poi add column if not exists nord_planimetria numeric;

-- ── 5 · QUELLO CHE LEGGE IL TELEFONO ────────────────────────────────
-- Il piano di ripresa di un luogo: leggero, senza testi né traduzioni,
-- fatto per essere scaricato una volta sul sagrato e portato dentro.
create or replace view public.v_piano_rilievo as
select s.id, s.poi_id, s.titolo, s.ordine, s.pos_x, s.pos_y,
       s.stato_rilievo, s.toccata_il, s.rilievo_id,
       (coalesce(s.panorama,'') <> '') as ha_panorama,
       s.foto_campo, s.nota_campo, s.lat_campo, s.lng_campo,
       p.nome as luogo, p.site_plan, p.lat as poi_lat, p.lng as poi_lng, p.nord_planimetria
  from public.story_tour_scene s
  join public.story_poi p on p.id = s.poi_id
 order by s.poi_id, s.ordine, s.id;

-- La regia: a che punto è ogni luogo con le riprese
create or replace view public.v_rilievo_quadro as
select p.id as poi_id, p.nome, p.comune,
       count(*)                                                    as scene,
       count(*) filter (where s.stato_rilievo = 'da_riprendere')   as da_riprendere,
       count(*) filter (where s.stato_rilievo = 'scattata')        as scattate,
       count(*) filter (where s.stato_rilievo = 'abbinata')        as abbinate,
       count(*) filter (where s.stato_rilievo = 'pubblicata')      as pubblicate,
       max(s.toccata_il)                                           as ultimo_tocco
  from public.story_tour_scene s
  join public.story_poi p on p.id = s.poi_id
 group by p.id, p.nome, p.comune
 order by (count(*) filter (where s.stato_rilievo in ('da_riprendere','scattata'))) desc, p.nome;

commit;

-- =====================================================================
-- VERIFICA · solo SELECT
-- =====================================================================
select 'quadro' as controllo, * from public.v_rilievo_quadro;
select 'incoerenze' as controllo, id, titolo, attivo, stato_rilievo
  from public.story_tour_scene
 where (panorama is null and attivo is true)
 order by id;
